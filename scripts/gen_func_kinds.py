#!/usr/bin/env python3
"""Generate expressions/kinds_funcs_gen.go from upstream exp.ALL_FUNCTIONS.

Upstream's base parser resolves every Func subclass's sql_names() to a typed node through
parser.Parser.FUNCTIONS (core.py:1663 from_arg_list). The hand-written tables in
expressions/kinds.go and expressions/functions.go cover only the Kinds earlier slices needed, so
every other function parsed as Anonymous and no dialect generator override could fire on it. This
script emits, for each upstream Func class the Go tables do not know:

  - a Kind constant (numbered from kindFuncGenBase, so the hand-written iota block never moves),
  - its className / argTypes / traitsOf / varLenArgs rows,
  - its upstream _sql_names[0] in SQLNames (what the base generator renders),
  - a FunctionByName entry per sql name whose upstream builder is the plain from_arg_list.

Names with a custom upstream builder (build_* helpers) and classes behind FUNCTION_PARSERS are
skipped and listed in the file header: they need a hand port. Existing Kinds only gain their
missing from_arg_list names. Run after scripts/fetch-reference.sh:

    PYTHONPATH=.reference/sqlglot-v30.17.0 python3 scripts/gen_func_kinds.py && gofmt -w expressions/kinds_funcs_gen.go
"""

import re
import sys
from pathlib import Path

try:
    from sqlglot import exp, parser
except ImportError:
    sys.exit("Run scripts/fetch-reference.sh first, then PYTHONPATH=.reference/sqlglot-v30.17.0 python3 ...")

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "expressions" / "kinds_funcs_gen.go"
KIND_BASE = 10000

TRAITS = {
    "Condition": "TraitCondition",
    "Predicate": "TraitPredicate",
    "Binary": "TraitBinary",
    "Connector": "TraitConnector",
    "Func": "TraitFunc",
    "AggFunc": "TraitAggFunc",
    "Unary": "TraitUnary",
    "UDTF": "TraitUDTF",
    "DerivedTable": "TraitDerivedTable",
}


def go_known():
    classes = set()
    for path in (ROOT / "expressions").glob("*.go"):
        if path.name == OUT.name or path.name.endswith("_test.go"):
            continue
        classes.update(re.findall(r'^\s*Kind\w+:\s+"(\w+)",', path.read_text(), re.M))
    names = set(re.findall(r'^\s+"([A-Z0-9_]+)":', (ROOT / "expressions" / "functions.go").read_text(), re.M))
    return classes, names


def main():
    known_classes, known_names = go_known()
    F = parser.Parser.FUNCTIONS
    special = {n for n in parser.Parser.FUNCTION_PARSERS}
    skipped_special, skipped_custom = [], []
    new_classes, extra_names = [], []

    for cls in sorted(exp.ALL_FUNCTIONS, key=lambda c: c.__name__):
        name = cls.__name__
        if name.startswith("Anonymous"):
            continue
        sql_names = cls.sql_names()
        if any(n in special for n in sql_names):
            skipped_special.append(name)
            continue
        plain = [n for n in sql_names if n in F and getattr(F[n], "__name__", "") == "from_arg_list"]
        custom = [n for n in sql_names if n not in plain]
        if custom:
            skipped_custom.extend(custom)
        wanted = [n for n in plain if n not in known_names]
        if name in known_classes:
            extra_names.extend((n, name) for n in wanted)
            continue
        keys = list(cls.arg_types)
        var_len = bool(cls.is_var_len_args)
        if var_len and cls.var_len_arg_key != keys[-1]:
            # Go FromArgList maps the trailing spec as the variadic one; the flags after the
            # variadic key are never positional, so moving it last keeps output identical.
            keys.remove(cls.var_len_arg_key)
            keys.append(cls.var_len_arg_key)
        bases = [b.__name__ for b in cls.__mro__[1:]]
        traits = [TRAITS[b] for b in TRAITS if b in bases]
        new_classes.append({
            "class": name,
            "sql_name": sql_names[0],
            "names": wanted,
            "args": [(k, bool(cls.arg_types[k])) for k in keys],
            "traits": traits,
            "var_len": var_len,
        })

    lines = [
        "// Code generated by scripts/gen_func_kinds.py from the pinned upstream; DO NOT EDIT.",
        "//",
        "// Skipped (FUNCTION_PARSERS grammar): " + ", ".join(skipped_special),
        "// Skipped (custom upstream builder, hand port): " + ", ".join(sorted(set(skipped_custom))),
        "",
        "package expressions",
        "",
        "const kindFuncGenBase Kind = %d" % KIND_BASE,
        "",
        "const (",
    ]
    for i, c in enumerate(new_classes):
        lines.append("\tKind%s Kind = kindFuncGenBase + %d" % (c["class"], i))
    lines += [")", "", "type generatedFunc struct {", "\tkind    Kind", "\tclass   string", "\tsqlName string",
              "\tnames   []string", "\targs    []argSpec", "\ttraits  Trait", "\tvarLen  bool", "}", "",
              "var generatedFuncs = []generatedFunc{"]
    for c in new_classes:
        args = ", ".join('{"%s", %s}' % (k, "true" if r else "false") for k, r in c["args"])
        names = ", ".join('"%s"' % n for n in c["names"])
        traits = " | ".join(c["traits"]) or "0"
        lines.append('\t{Kind%s, "%s", "%s", []string{%s}, []argSpec{%s}, %s, %s},' % (
            c["class"], c["class"], c["sql_name"], names, args, traits, "true" if c["var_len"] else "false"))
    lines += ["}", "", "var generatedFuncNames = map[string]Kind{"]
    for n, cls in extra_names:
        lines.append('\t"%s": Kind%s,' % (n, cls))
    lines += ["}", "", "func init() {",
              "\tfor _, f := range generatedFuncs {",
              "\t\tclassName[f.kind] = f.class",
              "\t\targTypes[f.kind] = f.args",
              "\t\ttraitsOf[f.kind] = f.traits",
              "\t\tSQLNames[f.kind] = f.sqlName",
              "\t\tif f.varLen {",
              "\t\t\tvarLenArgs[f.kind] = true",
              "\t\t}",
              "\t\tfor _, n := range f.names {",
              "\t\t\tFunctionByName[n] = genericFunction(f.kind)",
              "\t\t}",
              "\t}",
              "\tfor n, k := range generatedFuncNames {",
              "\t\tFunctionByName[n] = genericFunction(k)",
              "\t}",
              "}", ""]
    OUT.write_text("\n".join(lines))
    print("wrote %s: %d new kinds, %d names on existing kinds, skipped %d special / %d custom" % (
        OUT.relative_to(ROOT), len(new_classes), len(extra_names), len(skipped_special), len(set(skipped_custom))),
        file=sys.stderr)


if __name__ == "__main__":
    main()
